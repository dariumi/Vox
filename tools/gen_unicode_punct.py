#!/usr/bin/env python3
"""Generates src/unicode_punct.inc: the ranges of \\p{P} and \\p{S} (punctuation and symbols), for the CosyVoice text
frontend (is_only_punctuation). Usage: python tools/gen_unicode_punct.py > src/unicode_punct.inc"""
import unicodedata

out, start = [], None
for cp in range(0x110000):
    ok = unicodedata.category(chr(cp))[0] in "PS"
    if ok and start is None:
        start = cp
    elif not ok and start is not None:
        out.append((start, cp - 1))
        start = None
print(f"// Generated by tools/gen_unicode_punct.py, Unicode {unicodedata.unidata_version}: \\p{{P}} | \\p{{S}}")
print("static const uint32_t kPunctSym[][2] = {")
line = "   "
for lo, hi in out:
    item = f" {{0x{lo:X},0x{hi:X}}},"
    if len(line) + len(item) > 110:
        print(line)
        line = "   "
    line += item
print(line)
print("};")
print("static const size_t kPunctSym_N = sizeof(kPunctSym) / sizeof(kPunctSym[0]);")
