#!/usr/bin/env python3
"""Generates src/unicode_word.inc: the ranges of \\w as Unicode regexes define it (Alphabetic, marks, decimal digits, connector
punctuation, join controls — the `regex` module and Rust's regex agree), for the Whitespace pre-tokenizer of HF tokenizers.
Usage: python tools/gen_unicode_word.py > src/unicode_word.inc"""
import unicodedata

import regex

pat = regex.compile(r"\w")
out, start = [], None
for cp in range(0x110000):
    ok = not (0xD800 <= cp <= 0xDFFF) and bool(pat.match(chr(cp)))   # surrogates are not characters
    if ok and start is None:
        start = cp
    elif not ok and start is not None:
        out.append((start, cp - 1))
        start = None
if start is not None:
    out.append((start, 0x10FFFF))
print(f"// Generated by tools/gen_unicode_word.py (regex {regex.__version__}, Unicode {unicodedata.unidata_version}): \\w")
print("static const uint32_t kWordCh[][2] = {")
line = "   "
for lo, hi in out:
    item = f" {{0x{lo:X},0x{hi:X}}},"
    if len(line) + len(item) > 110:
        print(line)
        line = "   "
    line += item
print(line)
print("};")
print("static const size_t kWordCh_N = sizeof(kWordCh) / sizeof(kWordCh[0]);")
